"""
Вспомогательные утилиты общего назначения.

Содержит функции для преобразования типов данных и другие общие операции.
"""


def transform_to_int(value):
    """
    Преобразует значение в целое число.

    Args:
        value: Значение любого типа для преобразования

    Returns:
        int: Преобразованное целое число или None в случае ошибки
    """
    try:
        return int(float(value))
    except:
        return None